"""Offline comparison of retained receipts with exported physical materializations."""
from __future__ import annotations

from datetime import date, datetime, timezone
from decimal import Decimal
import json
import struct

from .recovery import child, digest_file
from .repository import payload_hash


def _scalar(value, kind):
    if value is None:
        return None
    if kind.endswith("[]"):
        return [_scalar(item, kind[:-2]) for item in value]
    if kind.startswith(("vector(", "halfvec(")):
        code = "!e" if kind.startswith("halfvec") else "!f"
        return [struct.unpack(code, struct.pack(code, float(item)))[0] for item in json.loads(value)]
    if kind.startswith("timestamp"):
        stamp = datetime.fromisoformat(value)
        return stamp.astimezone(timezone.utc) if stamp.tzinfo else stamp
    if kind == "date":
        return date.fromisoformat(value)
    if kind.startswith(("numeric", "decimal")):
        return Decimal(value)
    if kind in {"smallint", "integer", "bigint"}:
        return int(value)
    if kind == "real":
        return struct.unpack("!f", struct.pack("!f", float(value)))[0]
    if kind == "double precision":
        return float(value)
    if kind == "boolean" or kind.startswith(("text", "character varying", "character(")):
        return value
    raise ValueError("unsupported retained receipt materialization type: " + kind)


def runtime_rows(table):
    """Reproduce raw asyncpg + pgvector values used by the pinned receipt encoder.

    SQL NULL and JSON null differ in asyncpg. JSON text is exported alongside
    the exact rows in the same fenced query, never regenerated by Python.
    """
    texts = table.get("json_text_columns", [])
    if len(texts) != len(table["rows_json"]):
        raise ValueError("receipt materialization lacks exact JSON text projection")
    json_columns = {column["name"] for column in table["columns"] if column["type"] in {"json", "jsonb"}}
    result = []
    for encoded, raw in zip(table["rows_json"], texts, strict=True):
        row = json.loads(encoded, parse_float=Decimal, parse_int=Decimal)
        plain = json.loads(encoded)
        if set(raw) != json_columns:
            raise ValueError("receipt JSON materialization column inventory differs")
        converted = {}
        for column in table["columns"]:
            name, kind = column["name"], column["type"]
            if name in json_columns:
                value = raw[name]
                if (json.loads(value) if value is not None else None) != plain[name]:
                    raise ValueError("receipt JSON materialization differs from exact rows")
                converted[name] = value
            else:
                converted[name] = _scalar(row[name], kind)
        result.append(converted)
    return result


def verify_receipt_closure(package, catalog, postgres, graph):
    from papervault.knowledge.store.catalog_adapter import _inventory, _graph_inventory, _tombstones

    tables = catalog["tables"]
    receipts = {row["receipt"]["namespace"]: row["receipt"] for row in tables["knowledge_receipts"]}
    ids = {row["receipt_id"] for row in tables["knowledge_receipts"]}
    if len(receipts) != len(tables["knowledge_receipts"]):
        raise ValueError("retained receipt namespace is duplicated")
    # Validate all sealed history, including candidates, inherited generations
    # and recovery work. Unsealed attempts are preserved without granting credit.
    for row in tables["knowledge_receipts"]:
        receipt = row["receipt"]
        if (row["digest"] != payload_hash(receipt) or row["receipt_id"] != receipt["receipt_id"]
                or not receipt.get("sealed") or not receipt.get("durable")):
            raise ValueError("retained receipt digest or sealing differs")
        layers = receipt["aggregate_layers"]
        if not layers or layers[-1] != receipt["namespace"] or len(set(layers)) != len(layers):
            raise ValueError("retained receipt ancestor chain is invalid")
        for index, namespace in enumerate(layers):
            if namespace not in receipts or receipts[namespace]["aggregate_layers"] != layers[:index + 1]:
                raise ValueError("retained receipt ancestor is absent or changed")
        for field in ("selected_unit_receipts", "base_selected_unit_receipts"):
            if not set(receipt.get(field, {}).values()).issubset(ids):
                raise ValueError("retained selected receipt is absent")
    for row in tables["derivations"]:
        if row.get("receipt_id") and row["receipt_id"] not in ids:
            raise ValueError("retained derivation receipt is absent")
    for row in tables["generation_manifests"]:
        if not set(row["manifest"].get("aggregate_layers", [])).issubset(receipts):
            raise ValueError("retained generation receipt ancestor is absent")
    inputs = {row["consumed_input_revision"]: row["manifest"] for row in tables["input_manifests"]}
    pg_rows = {}
    nodes = {row["id"]: row for row in graph.get("nodes", [])}
    for namespace, receipt in receipts.items():
        for output in receipt["output_inventory"]:
            role, store = output["role"], output["store"]
            if store == "postgres":
                name = output["verification"]["evidence"].get("backend_table")
                if name not in postgres.get("tables", {}):
                    raise ValueError("retained receipt backend table materialization absent")
                if name not in pg_rows:
                    pg_rows[name] = runtime_rows(postgres["tables"][name])
                values = [row for row in pg_rows[name] if row["workspace"] == namespace]
                actual = _inventory(role, store, namespace, values, [str(row["id"]) for row in values], "snapshot")
            elif store == "neo4j":
                selected_nodes = [{**row["properties"], "id": row["properties"]["entity_id"]} for row in nodes.values()
                    if "PaperVaultCatalogEntity" in row["labels"] and row["properties"].get("_pv_namespace") == namespace]
                edges = []
                for edge in graph["relationships"]:
                    source, target = nodes[edge["source"]], nodes[edge["target"]]
                    if (edge["type"] == "DIRECTED" and edge["properties"].get("_pv_namespace") == namespace
                            and all("PaperVaultCatalogEntity" in node["labels"]
                                and node["properties"].get("_pv_namespace") == namespace for node in (source, target))):
                        edges.append({**edge["properties"], "source": source["properties"]["entity_id"],
                                      "target": target["properties"]["entity_id"]})
                actual = _graph_inventory(namespace, selected_nodes, edges, "snapshot")
            elif store == "catalog" and role == "tombstones":
                values = _tombstones(row for row in tables["knowledge_output_tombstones"] if row["namespace"] == namespace)
                actual = _inventory(role, store, namespace, values, [row["role"] + ":" + row["output_id"] for row in values], "snapshot")
            elif store == "catalog_inputs":
                artifact = next(row for row in inputs[receipt["consumed_input_revision"]]["artifacts"]
                                if row["artifact_id"] == output["output_id"])
                actual = digest_file(child(package, "inputs/catalog_inputs/" + artifact["sha256"]))
            else:
                raise ValueError("unsupported retained receipt materialization store")
            if any(actual[key] != output[key] for key in ("sha256", "byte_length")):
                raise ValueError("retained receipt materialization checksum differs: " + namespace + ":" + role)
